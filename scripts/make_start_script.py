"""
scripts/make_start_script.py

Generates `scripts/start_bot.bat`: a Windows launcher with ABSOLUTE paths (the repository and the Python interpreter), so Windows Task
Scheduler or the `shell:startup` folder can start the bot without any working-directory or PATH set-up. A bare `python` is avoided on
purpose: in PowerShell it can hit the Windows App Execution Alias stub and exit silently.

    python -m scripts.make_start_script                      # interpreter = the one running this script
    python -m scripts.make_start_script --python C:\\path\\to\\python.exe

The generated launcher
  - appends everything the bot prints (its log lines already carry timestamps) to `logsot.log`, plus its own timestamped
    start / exit / restart lines;
  - restarts the bot after a crash (any non-zero exit code, e.g. a network drop at logon): it waits 10 seconds and tries again, at most
    MAX_RESTARTS times in total, then exits with the last exit code. A clean exit (code 0) is never restarted.
It contains no secret; the bot still reads `.env` from the repository directory it switches to.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

__all__ = ["render_start_script", "main"]

REPO_ROOT = Path(__file__).resolve().parent.parent
TARGET = REPO_ROOT / "scripts" / "start_bot.bat"
MAX_RESTARTS = 3
RESTART_DELAY_SECONDS = 10


def render_start_script(repo_root: Path | str, python_exe: Path | str, *, max_restarts: int = MAX_RESTARTS,
                        restart_delay_seconds: int = RESTART_DELAY_SECONDS) -> str:
    for value in (str(repo_root), str(python_exe)):
        if any(ch in value for ch in '"%&|<>^\r\n'):
            raise ValueError(f"unsupported character in path: {value!r}")
    log = r"logs\bot.log"
    lines = [
        "@echo off",
        "rem Generated by scripts/make_start_script.py -- regenerate it instead of editing (absolute paths for this machine).",
        "rem Starts the AI Coach and Keyholder Discord bot from the repository directory (it reads .env there), appends all output",
        f"rem to {log} and restarts it after a crash: wait {restart_delay_seconds} s, at most {max_restarts} restarts.",
        "setlocal",
        "title AI Coach Keyholder bot",
        f"cd /d \"{repo_root}\" || exit /b 1",
        "if not exist logs mkdir logs",
        "set RESTARTS=0",
        ":run",
        f">> \"{log}\" echo [%date% %time%] start_bot.bat: starting the bot, restarts so far %RESTARTS%",
        f"\"{python_exe}\" -m bot.discord_bot >> \"{log}\" 2>&1",
        "set CODE=%ERRORLEVEL%",
        f">> \"{log}\" echo [%date% %time%] start_bot.bat: the bot exited with code %CODE%",
        "if \"%CODE%\"==\"0\" goto done",
        f"if %RESTARTS% GEQ {max_restarts} goto giveup",
        "set /a RESTARTS+=1",
        f">> \"{log}\" echo [%date% %time%] start_bot.bat: restarting in {restart_delay_seconds} seconds, restart %RESTARTS% of {max_restarts}",
        f"ping -n {restart_delay_seconds + 1} 127.0.0.1 >nul",
        "goto run",
        ":giveup",
        f">> \"{log}\" echo [%date% %time%] start_bot.bat: giving up after {max_restarts} restarts",
        ":done",
        "endlocal & exit /b %CODE%",
        "",
    ]
    return "\r\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m scripts.make_start_script", description="Generate scripts/start_bot.bat.")
    parser.add_argument("--python", default=sys.executable, help="absolute path of python.exe (default: the running interpreter)")
    args = parser.parse_args(argv)
    python_exe = Path(args.python)
    if not python_exe.is_absolute() or not python_exe.is_file():
        print(f"Refused: {python_exe} is not an existing absolute path.")
        return 2
    TARGET.write_bytes(render_start_script(REPO_ROOT, python_exe).encode("ascii"))
    print(f"Wrote {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
